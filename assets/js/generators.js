function buildAuthHeader(authType, keyName, keyVal) {
  const key = keyVal || 'your_api_key_here';
  switch (authType) {
    case 'bearer':        return `Authorization: Bearer ${key}`;
    case 'api_key_header': return `x-api-key: ${key}`;
    case 'basic':         return `Authorization: Basic <base64(username:${key})>`;
    case 'oauth2':        return `Authorization: Bearer <oauth2_access_token>`;
    case 'jwt':           return `Authorization: Bearer <jwt_token>`;
    default:              return '';
  }
}

function snipJS(form, preset) {
  const baseUrl = form.baseUrl || preset.baseUrl || 'https://api.example.com/v1';
  const keyName = preset.keyName || 'API_KEY';
  const authHeader = buildAuthHeader(form.authType, keyName, form.apiKey);

  return `// Generated by api-config-gen
// Vanilla JS (Fetch API)

const API_BASE_URL = '${baseUrl}';
const ${keyName} = process.env.${keyName} || 'your_api_key_here';

const headers = {
  'Content-Type': 'application/json',${authHeader ? `\n  '${authHeader.split(':')[0].trim()}': '${authHeader.split(':').slice(1).join(':').trim()}',` : ''}
};

async function apiRequest(endpoint, options = {}) {
  const url = \`\${API_BASE_URL}\${endpoint}\`;
  const config = {
    ...options,
    headers: { ...headers, ...(options.headers || {}) },
  };

  let attempts = 0;
  while (attempts < ${form.retries || 3}) {
    try {
      const res = await fetch(url, config);
      if (!res.ok) throw new Error(\`HTTP \${res.status}: \${res.statusText}\`);
      return await res.json();
    } catch (err) {
      attempts++;
      if (attempts >= ${form.retries || 3}) throw err;
      await new Promise(r => setTimeout(r, 1000 * attempts));
    }
  }
}

// Usage:
// const data = await apiRequest('/endpoint', { method: 'GET' });`;
}

function snipNodeAxios(form, preset) {
  const baseUrl = form.baseUrl || preset.baseUrl || 'https://api.example.com/v1';
  const keyName = preset.keyName || 'API_KEY';

  return `// Generated by api-config-gen
// Node.js — Axios

const axios = require('axios');

const client = axios.create({
  baseURL: process.env.API_BASE_URL || '${baseUrl}',
  timeout: ${form.timeout || 30000},
  headers: {
    'Content-Type': 'application/json',
    'Authorization': \`Bearer \${process.env.${keyName}}\`,
  },
});

// Retry interceptor
let retryCount = 0;
client.interceptors.response.use(null, async (error) => {
  if (retryCount < ${form.retries || 3}) {
    retryCount++;
    await new Promise(r => setTimeout(r, 1000 * retryCount));
    return client.request(error.config);
  }
  return Promise.reject(error);
});

module.exports = client;

// Usage:
// const { data } = await client.get('/endpoint');`;
}

function snipPython(form, preset) {
  const baseUrl = form.baseUrl || preset.baseUrl || 'https://api.example.com/v1';
  const keyName = preset.keyName || 'API_KEY';

  return `# Generated by api-config-gen
# Python — requests

import os
import time
import requests
from requests.adapters import HTTPAdapter
from urllib3.util.retry import Retry

BASE_URL = os.getenv('API_BASE_URL', '${baseUrl}')
API_KEY  = os.getenv('${keyName}', 'your_api_key_here')
TIMEOUT  = ${(form.timeout || 30000) / 1000}

session = requests.Session()
retry_strategy = Retry(
    total=${form.retries || 3},
    backoff_factor=1,
    status_forcelist=[429, 500, 502, 503, 504],
)
adapter = HTTPAdapter(max_retries=retry_strategy)
session.mount('https://', adapter)

HEADERS = {
    'Content-Type': 'application/json',
    'Authorization': f'Bearer {API_KEY}',
}

def api_request(endpoint, method='GET', **kwargs):
    url = f'{BASE_URL}{endpoint}'
    response = session.request(
        method, url,
        headers=HEADERS,
        timeout=TIMEOUT,
        **kwargs
    )
    response.raise_for_status()
    return response.json()

# Usage:
# data = api_request('/endpoint')`;
}

function snipGo(form, preset) {
  const baseUrl = form.baseUrl || preset.baseUrl || 'https://api.example.com/v1';
  const keyName = preset.keyName || 'API_KEY';

  return `// Generated by api-config-gen
// Go — net/http

package main

import (
    "encoding/json"
    "fmt"
    "io"
    "net/http"
    "os"
    "time"
)

var (
    baseURL = getEnv("API_BASE_URL", "${baseUrl}")
    apiKey  = getEnv("${keyName}", "your_api_key_here")
    client  = &http.Client{Timeout: ${(form.timeout || 30000) / 1000} * time.Second}
)

func getEnv(key, fallback string) string {
    if v := os.Getenv(key); v != "" { return v }
    return fallback
}

func apiRequest(endpoint string) (map[string]interface{}, error) {
    req, err := http.NewRequest("GET", baseURL+endpoint, nil)
    if err != nil { return nil, err }

    req.Header.Set("Authorization", "Bearer "+apiKey)
    req.Header.Set("Content-Type", "application/json")

    resp, err := client.Do(req)
    if err != nil { return nil, err }
    defer resp.Body.Close()

    if resp.StatusCode >= 400 {
        return nil, fmt.Errorf("HTTP %d", resp.StatusCode)
    }

    body, _ := io.ReadAll(resp.Body)
    var result map[string]interface{}
    json.Unmarshal(body, &result)
    return result, nil
}`;
}

function snipPHP(form, preset) {
  const baseUrl = form.baseUrl || preset.baseUrl || 'https://api.example.com/v1';

  return `<?php
// Generated by api-config-gen
// PHP — cURL

define('API_BASE_URL', getenv('API_BASE_URL') ?: '${baseUrl}');
define('API_KEY',      getenv('${preset.keyName || 'API_KEY'}') ?: 'your_api_key_here');
define('API_TIMEOUT',  ${(form.timeout || 30000) / 1000});

function apiRequest(string $endpoint, string $method = 'GET', array $body = []): array {
    $url = API_BASE_URL . $endpoint;
    $ch = curl_init($url);

    $headers = [
        'Content-Type: application/json',
        'Authorization: Bearer ' . API_KEY,
    ];

    curl_setopt_array($ch, [
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_HTTPHEADER     => $headers,
        CURLOPT_CUSTOMREQUEST  => $method,
        CURLOPT_TIMEOUT        => API_TIMEOUT,
        CURLOPT_FOLLOWLOCATION => true,
    ]);

    if (!empty($body)) {
        curl_setopt($ch, CURLOPT_POSTFIELDS, json_encode($body));
    }

    $response = curl_exec($ch);
    $httpCode = curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);

    if ($httpCode >= 400) throw new RuntimeException("HTTP Error: $httpCode");
    return json_decode($response, true);
}`;
}

function snipRuby(form, preset) {
  const baseUrl = form.baseUrl || preset.baseUrl || 'https://api.example.com/v1';

  return `# Generated by api-config-gen
# Ruby — Net::HTTP

require 'net/http'
require 'json'
require 'uri'

class ApiClient
  BASE_URL = ENV.fetch('API_BASE_URL', '${baseUrl}')
  API_KEY  = ENV.fetch('${preset.keyName || 'API_KEY'}', 'your_api_key_here')
  TIMEOUT  = ${(form.timeout || 30000) / 1000}

  def self.request(endpoint, method: :get, body: nil)
    uri  = URI("#{BASE_URL}#{endpoint}")
    http = Net::HTTP.new(uri.host, uri.port)
    http.use_ssl    = uri.scheme == 'https'
    http.read_timeout = TIMEOUT

    req = case method
          when :get    then Net::HTTP::Get.new(uri)
          when :post   then Net::HTTP::Post.new(uri)
          when :put    then Net::HTTP::Put.new(uri)
          when :delete then Net::HTTP::Delete.new(uri)
          end

    req['Content-Type']  = 'application/json'
    req['Authorization'] = "Bearer #{API_KEY}"
    req.body = body.to_json if body

    res = http.request(req)
    raise "HTTP #{res.code}" unless res.is_a?(Net::HTTPSuccess)
    JSON.parse(res.body)
  end
end`;
}

