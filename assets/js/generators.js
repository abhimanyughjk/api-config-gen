function generateConfig(form) {
  const data = buildConfigData(form);
  switch (form.format) {
    case 'env':    return genENV(data);
    case 'json':   return genJSON(data);
    case 'yaml':   return genYAML(data);
    case 'toml':   return genTOML(data);
    case 'js':     return genJS(data);
    case 'python': return genPython(data);
    case 'go':     return genGo(data);
    default:       return genENV(data);
  }
}

function generateSnippet(form) {
  const preset = API_PRESETS[form.provider] || API_PRESETS.custom;
  switch (form.language) {
    case 'js':          return snipJS(form, preset);
    case 'node_axios':  return snipNodeAxios(form, preset);
    case 'python':      return snipPython(form, preset);
    case 'go':          return snipGo(form, preset);
    case 'php':         return snipPHP(form, preset);
    case 'ruby':        return snipRuby(form, preset);
    default:            return snipJS(form, preset);
  }
}

