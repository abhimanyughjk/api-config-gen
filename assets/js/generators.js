function buildConfigData(form) {
  const preset = API_PRESETS[form.provider] || API_PRESETS.custom;
  const baseUrl = form.baseUrl || preset.baseUrl || 'https://api.example.com/v1';
  const apiKey  = form.apiKey  || 'your_api_key_here';

  const data = {
    API_BASE_URL:       baseUrl,
    API_TIMEOUT:        String(form.timeout || 30000),
    API_RETRY_ATTEMPTS: String(form.retries || 3),
    RATE_LIMIT:         String(form.rateLimit || 60),
    AUTH_TYPE:          form.authType || 'bearer',
    [preset.keyName || 'API_KEY']: apiKey,
    ...preset.extra
  };

  return data;
}

function genENV(data) {
  const lines = ['# Generated by api-config-gen', '# https://abhimanyughjk.github.io/api-config-gen', ''];
  for (const [k, v] of Object.entries(data)) {
    lines.push(`${k}=${v}`);
  }
  return lines.join('\n');
}

function genJSON(data) {
  const obj = {};
  for (const [k, v] of Object.entries(data)) {
    const key = k.toLowerCase().replace(/_([a-z])/g, (_, c) => c.toUpperCase());
    obj[key] = isNaN(v) ? v : (v.includes('.') ? parseFloat(v) : parseInt(v, 10));
  }
  return JSON.stringify({ apiConfig: obj }, null, 2);
}

function genYAML(data) {
  const lines = ['# Generated by api-config-gen', 'api_config:'];
  for (const [k, v] of Object.entries(data)) {
    const key = k.toLowerCase();
    const val = isNaN(v) ? `"${v}"` : v;
    lines.push(`  ${key}: ${val}`);
  }
  return lines.join('\n');
}

function genTOML(data) {
  const lines = ['# Generated by api-config-gen', '[api_config]', ''];
  for (const [k, v] of Object.entries(data)) {
    const key = k.toLowerCase();
    const val = isNaN(v) ? `"${v}"` : v;
    lines.push(`${key} = ${val}`);
  }
  return lines.join('\n');
}

function genJS(data) {
  const lines = ['// Generated by api-config-gen', '// https://abhimanyughjk.github.io/api-config-gen', '', 'const apiConfig = {'];
  for (const [k, v] of Object.entries(data)) {
    const key = k.toLowerCase().replace(/_([a-z])/g, (_, c) => c.toUpperCase());
    const val = isNaN(v) ? `'${v}'` : v;
    lines.push(`  ${key}: ${val},`);
  }
  lines.push('};', '', 'module.exports = apiConfig;');
  return lines.join('\n');
}

function genPython(data) {
  const lines = ['# Generated by api-config-gen', '# https://abhimanyughjk.github.io/api-config-gen', '', 'import os', '', 'API_CONFIG = {'];
  for (const [k, v] of Object.entries(data)) {
    const val = isNaN(v) ? `os.getenv('${k}', '${v}')` : v;
    lines.push(`    '${k}': ${val},`);
  }
  lines.push('}');
  return lines.join('\n');
}

function genGo(data) {
  const lines = [
    '// Generated by api-config-gen',
    '// https://abhimanyughjk.github.io/api-config-gen',
    '',
    'package config',
    '',
    'import "os"',
    '',
    'type APIConfig struct {'
  ];

  const fields = [];
  for (const k of Object.keys(data)) {
    const field = k.split('_').map(w => w[0].toUpperCase() + w.slice(1).toLowerCase()).join('');
    fields.push(`    ${field} string`);
  }
  lines.push(...fields, '}', '', 'func Load() APIConfig {', '    return APIConfig{');
  for (const [k, v] of Object.entries(data)) {
    const field = k.split('_').map(w => w[0].toUpperCase() + w.slice(1).toLowerCase()).join('');
    lines.push(`        ${field}: os.Getenv("${k}"),`);
  }
  lines.push('    }', '}');
  return lines.join('\n');
}

